// Shared OpenAPI pre-processing for the type-gen + drift-check pipeline.
//
// Why this exists: the API's OpenAPI document emits `discriminator.mapping`
// values as local JSON pointers (e.g. "#/oneOf/0"). OpenAPI 3.1 does NOT permit
// JSON-Pointer-into-a-sibling-`oneOf` as a mapping target — mapping values must
// be component schema names or URI references to schemas. Redocly's bundler
// (used internally by openapi-typescript) rejects these as unresolvable refs.
//
// Each affected `oneOf` member already carries a `const` on its discriminator
// property, which is sufficient for both validators and codegen to narrow the
// union — so the offending `mapping` is dropped while `propertyName` is kept.
// This is a defensive boundary transform; the upstream document is unchanged.

/**
 * The banner prepended to `src/generated/types.ts`.
 *
 * It lives here, not in the two scripts that use it, because it was previously
 * hand-written in both: `gen-types.mjs` emits it and `check-types.mjs`
 * reconstructs it to diff against. Editing one and not the other reds the drift
 * gate over a file nobody touched, so the two copies were a defect waiting to
 * be triggered. One export, two importers, no way to desync.
 *
 * Plain ASCII on purpose: this banner ships inside the published package (the
 * file is in `files[]` and is inlined into `dist/index.d.ts`), so it is subject
 * to the same copy-quality rule as the rest of the published prose.
 * @type {string}
 */
export const GENERATED_HEADER = `// AUTO-GENERATED by openapi-typescript. Do not edit manually.
// Source: /.well-known/openapi.json (Curviate REST API)
// Regenerate: pnpm gen:types (requires pnpm dev running)
`;

/**
 * The forbidden substrate-vendor name, assembled from fragments so the literal
 * never appears in this public-repo source. The codegen guard greps the
 * generated output against this; the name itself is never written verbatim
 * anywhere in the package.
 * @returns {RegExp} a case-insensitive matcher for the forbidden vendor name
 */
export function forbiddenVendorPattern() {
  const needle = ["uni", "pi", "le"].join("");
  return new RegExp(needle, "i");
}

/**
 * Recursively strip any `discriminator.mapping` whose values are local
 * JSON pointers (`#/oneOf/N`). Mutates `node` in place. Returns the count
 * of mappings stripped (for observability).
 * @param {unknown} node
 * @returns {number}
 */
export function stripLocalDiscriminatorMappings(node) {
  let stripped = 0;
  const visit = (n) => {
    if (!n || typeof n !== "object") return;
    if (Array.isArray(n)) {
      for (const item of n) visit(item);
      return;
    }
    const disc = n.discriminator;
    if (disc && disc.mapping && typeof disc.mapping === "object") {
      const values = Object.values(disc.mapping);
      if (values.some((v) => typeof v === "string" && v.startsWith("#/oneOf/"))) {
        delete disc.mapping;
        stripped += 1;
      }
    }
    for (const key of Object.keys(n)) visit(n[key]);
  };
  visit(node);
  return stripped;
}

/**
 * openapi-typescript options shared by gen:types and check:types.
 *
 * `defaultNonNullable: false`: a property carrying a `default` stays optional
 * in the generated type. The default (true) typed the Sequence document's
 * `post`, `newer_than` and `reaction` as REQUIRED, so a valid document that
 * omits them (the server applies the default) did not compile against
 * `SequenceDocument`.
 */
export const TYPEGEN_OPTIONS = { defaultNonNullable: false };

/**
 * openapi-typescript 7.6.1 ignores `patternProperties` and renders such an
 * object as `Record<string, never>`, so the Sequence predicate
 * `{"contact.extra.<key>": {...}}` did not compile against `SequenceDocument`.
 * For type generation only, an object whose only members are
 * `patternProperties` gets that one pattern's schema as `additionalProperties`
 * (the key pattern is checked at run time by `validateSequence`). Mutates
 * `node`; the embedded schema is extracted before this runs.
 * @param {unknown} node
 * @returns {number} objects rewritten
 */
export function inlinePatternProperties(node) {
  let rewritten = 0;
  const visit = (n) => {
    if (!n || typeof n !== "object") return;
    if (Array.isArray(n)) {
      for (const item of n) visit(item);
      return;
    }
    const pp = n.patternProperties;
    if (pp && typeof pp === "object" && !n.properties && Object.keys(pp).length === 1) {
      n.additionalProperties = Object.values(pp)[0];
      delete n.patternProperties;
      rewritten += 1;
    }
    for (const key of Object.keys(n)) visit(n[key]);
  };
  visit(node);
  return rewritten;
}

/**
 * The Sequence document v1 JSON Schema as `src/sequence/schema.v1.json` holds
 * it: `components.schemas.SequenceDocument` of the OpenAPI document, key for
 * key (sdk/009 FR-010). Read before any transform above mutates the document.
 * @param {any} doc the raw OpenAPI document
 * @returns {string} pretty JSON plus a trailing newline
 */
export function sequenceSchemaJson(doc) {
  const schema = doc?.components?.schemas?.SequenceDocument;
  if (!schema) throw new Error("components.schemas.SequenceDocument missing from the OpenAPI document");
  return JSON.stringify(schema, null, 2) + "\n";
}
